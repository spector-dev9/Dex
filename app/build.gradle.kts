val generatedLicensesDir = layout.buildDirectory.dir("generated/licenses/assets")
val syncLicenses = tasks.register<Sync>("syncLicenses") {
    from(rootProject.layout.projectDirectory.dir("docs/licenses")) {
        include("NOTICES.md", "SOURCE-OFFER.md", "texts/*")
        into("licenses")
    }
    into(generatedLicensesDir)
}

val generatedRuntimeAssets = layout.buildDirectory.dir("generated/runtime/assets")
val syncRuntimeManifest = tasks.register<Sync>("syncRuntimeManifest") {
    // The installer reads the full pinned manifest (URLs, hashes, packages)
    // from assets/runtime-manifest.json; app/src/main/assets/manifest.json
    // keeps the slim RT-3 identity block checked by CI.
    from(rootProject.layout.projectDirectory.file("runtime/manifest.json")) {
        rename { "runtime-manifest.json" }
    }
    into(generatedRuntimeAssets)
}

/**
 * The APK-native runtime payloads (musl loader, PRoot, helper libraries) are
 * generated by `python scripts/stage-spike-harness.py`, which fetches and
 * SHA-256-verifies every pinned artifact. CI runs that staging script before
 * building :app; locally the same command applies.
 */
val stagedNativePayloads =
    File(rootProject.projectDir, "tests/spikes/harness/src/main/jniLibs/arm64-v8a")
val stagedRuntimeAssets =
    File(rootProject.projectDir, "tests/spikes/harness/src/main/assets/runtime-libs")

val generatedNativePayloadDir = layout.buildDirectory.dir("generated/runtime/jniLibs")
val stageNativePayloads = tasks.register<Sync>("stageNativePayloads") {
    // Locals only: closures that capture script state break the
    // configuration cache.
    val stagedLoader = File(stagedNativePayloads, "libldmusl.so")
    doFirst {
        if (!stagedLoader.isFile) {
            throw GradleException(
                "staged runtime payloads are missing ($stagedLoader); " +
                    "run `python scripts/stage-spike-harness.py` first",
            )
        }
    }
    from(stagedNativePayloads) {
        include("libldmusl.so", "libproot.so", "libproot_loader.so")
    }
    into(generatedNativePayloadDir.map { it.dir("arm64-v8a") })
}

val generatedRuntimeLibAssetsDir = layout.buildDirectory.dir("generated/runtime/lib-assets")
val stageRuntimeLibAssets = tasks.register<Sync>("stageRuntimeLibAssets") {
    val stagedTalloc = File(stagedRuntimeAssets, "libtalloc.so.2")
    doFirst {
        if (!stagedTalloc.isFile) {
            throw GradleException(
                "staged runtime payloads are missing ($stagedTalloc); " +
                    "run `python scripts/stage-spike-harness.py` first",
            )
        }
    }
    from(stagedRuntimeAssets) {
        include("libtalloc.so.2", "libandroid-shmem.so")
    }
    into(generatedRuntimeLibAssetsDir.map { it.dir("runtime-libs") })
}

